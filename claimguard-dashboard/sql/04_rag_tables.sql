-- Policy documents master list
CREATE OR REPLACE TABLE CLAIMGUARD.RAG.POLICY_DOCUMENTS (
    POLICY_DOC_ID   NUMBER AUTOINCREMENT PRIMARY KEY,
    POLICY_TYPE     VARCHAR(50) NOT NULL,
    POLICY_NUMBER   VARCHAR(50) NOT NULL,
    TITLE           VARCHAR(500) NOT NULL,
    SOURCE_URL      VARCHAR(1000),
    PAYER           VARCHAR(100) DEFAULT 'Medicare',
    JURISDICTION    VARCHAR(100),
    CREATED_AT      TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Policy versions with full text
CREATE OR REPLACE TABLE CLAIMGUARD.RAG.POLICY_VERSIONS (
    VERSION_ID      NUMBER AUTOINCREMENT PRIMARY KEY,
    POLICY_DOC_ID   NUMBER NOT NULL,
    VERSION_NUMBER  NUMBER NOT NULL DEFAULT 1,
    EFFECTIVE_DATE  DATE NOT NULL,
    END_DATE        DATE,
    REVISION_NOTES  VARCHAR(1000),
    RAW_TEXT        VARCHAR(16777216),
    CREATED_AT      TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Searchable chunks for Cortex Search
CREATE OR REPLACE TABLE CLAIMGUARD.RAG.POLICY_CHUNKS (
    CHUNK_ID        NUMBER AUTOINCREMENT PRIMARY KEY,
    VERSION_ID      NUMBER NOT NULL,
    POLICY_DOC_ID   NUMBER NOT NULL,
    POLICY_NUMBER   VARCHAR(50) NOT NULL,
    SECTION_HEADING VARCHAR(500),
    CHUNK_TEXT      VARCHAR(16777216) NOT NULL,
    CHUNK_ORDER     NUMBER NOT NULL,
    PAYER           VARCHAR(100) DEFAULT 'Medicare',
    JURISDICTION    VARCHAR(100),
    EFFECTIVE_DATE  DATE,
    END_DATE        DATE,
    CREATED_AT      TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Structured requirements for the rules engine
CREATE OR REPLACE TABLE CLAIMGUARD.RAG.POLICY_REQUIREMENTS (
    REQUIREMENT_ID    NUMBER AUTOINCREMENT PRIMARY KEY,
    VERSION_ID        NUMBER NOT NULL,
    POLICY_DOC_ID     NUMBER NOT NULL,
    POLICY_NUMBER     VARCHAR(50) NOT NULL,
    REQUIREMENT_CODE  VARCHAR(50),
    REQUIREMENT_TEXT  VARCHAR(5000) NOT NULL,
    REQUIREMENT_TYPE  VARCHAR(50),
    IS_TESTABLE       BOOLEAN DEFAULT TRUE,
    CHECK_SQL         VARCHAR(16777216),
    CREATED_AT        TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
