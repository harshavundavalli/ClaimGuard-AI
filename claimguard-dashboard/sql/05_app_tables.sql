-- ============================================================
-- ClaimGuard AI — Deployment Script 5: APP Tables
-- Prerequisites: Script 01
-- ============================================================

-- Incoming claims landing table
CREATE OR REPLACE TABLE CLAIMGUARD.RAW.INCOMING_CLAIMS (
    RAW_CLAIM_ID    NUMBER AUTOINCREMENT PRIMARY KEY,
    CLAIM_ID        NUMBER NOT NULL,
    PATIENT_ID      NUMBER NOT NULL,
    ENCOUNTER_ID    NUMBER NOT NULL,
    SOURCE_FILE     VARCHAR(500),
    RECEIVED_AT     TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    IS_PROCESSED    BOOLEAN DEFAULT FALSE
);

-- Review queue
CREATE OR REPLACE TABLE CLAIMGUARD.APP.REVIEW_QUEUE (
    QUEUE_ID        NUMBER AUTOINCREMENT PRIMARY KEY,
    CLAIM_ID        NUMBER NOT NULL,
    PATIENT_ID      NUMBER NOT NULL,
    ENCOUNTER_ID    NUMBER NOT NULL,
    QUEUE_STATUS    VARCHAR(30) DEFAULT 'PENDING',
    PRIORITY        NUMBER DEFAULT 5,
    QUEUED_AT       TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    STARTED_AT      TIMESTAMP_NTZ,
    COMPLETED_AT    TIMESTAMP_NTZ,
    CLAIM_VERSION   NUMBER DEFAULT 1,
    EVENT_ID        VARCHAR(100),
    RETRY_COUNT     NUMBER DEFAULT 0,
    MAX_RETRIES     NUMBER DEFAULT 3,
    ERROR_MESSAGE   VARCHAR(5000)
);

-- Agent review results
CREATE OR REPLACE TABLE CLAIMGUARD.APP.CLAIM_REVIEWS (
    REVIEW_ID           NUMBER AUTOINCREMENT PRIMARY KEY,
    QUEUE_ID            NUMBER NOT NULL,
    CLAIM_ID            NUMBER NOT NULL,
    REVIEW_VERSION      NUMBER DEFAULT 1,
    OVERALL_STATUS      VARCHAR(30),
    AGENT_VERSION       VARCHAR(50),
    MODEL_USED          VARCHAR(100),
    INPUT_SNAPSHOT      VARIANT,
    POLICY_VERSIONS_USED VARIANT,
    REVIEW_SUMMARY      VARCHAR(16777216),
    TOTAL_FINDINGS      NUMBER DEFAULT 0,
    PROCESSING_TIME_MS  NUMBER,
    ESTIMATED_COST      NUMBER(10,4),
    CREATED_AT          TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Per-requirement findings
CREATE OR REPLACE TABLE CLAIMGUARD.APP.REVIEW_FINDINGS (
    FINDING_ID      NUMBER AUTOINCREMENT PRIMARY KEY,
    REVIEW_ID       NUMBER NOT NULL,
    CLAIM_ID        NUMBER NOT NULL,
    REQUIREMENT_CODE VARCHAR(50),
    FINDING_STATUS  VARCHAR(30),
    FINDING_TYPE    VARCHAR(50),
    FINDING_TEXT    VARCHAR(5000) NOT NULL,
    EVIDENCE_TEXT   VARCHAR(5000),
    POLICY_CITATION VARCHAR(1000),
    POLICY_CHUNK_ID NUMBER,
    CONFIDENCE      VARCHAR(20),
    IS_DETERMINISTIC BOOLEAN DEFAULT FALSE,
    CREATED_AT      TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Reviewer decisions
CREATE OR REPLACE TABLE CLAIMGUARD.APP.REVIEW_ACTIONS (
    ACTION_ID       NUMBER AUTOINCREMENT PRIMARY KEY,
    REVIEW_ID       NUMBER NOT NULL,
    FINDING_ID      NUMBER,
    ACTION_TYPE     VARCHAR(30) NOT NULL,
    REVIEWER_USER   VARCHAR(100) NOT NULL,
    REVIEWER_ROLE   VARCHAR(100),
    ACTION_NOTES    VARCHAR(5000),
    CREATED_AT      TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Pipeline tracking
CREATE OR REPLACE TABLE CLAIMGUARD.APP.PIPELINE_RUNS (
    RUN_ID          NUMBER AUTOINCREMENT PRIMARY KEY,
    RUN_TYPE        VARCHAR(50) NOT NULL,
    RUN_STATUS      VARCHAR(30) DEFAULT 'RUNNING',
    CLAIMS_PROCESSED NUMBER DEFAULT 0,
    CLAIMS_FAILED   NUMBER DEFAULT 0,
    STARTED_AT      TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    COMPLETED_AT    TIMESTAMP_NTZ,
    ERROR_LOG       VARCHAR(16777216),
    METADATA        VARIANT
);

-- Dead-letter queue
CREATE OR REPLACE TABLE CLAIMGUARD.APP.DEAD_LETTER_QUEUE (
    DLQ_ID          NUMBER AUTOINCREMENT PRIMARY KEY,
    CLAIM_ID        NUMBER,
    PATIENT_ID      NUMBER,
    ENCOUNTER_ID    NUMBER,
    ERROR_MESSAGE   VARCHAR(5000),
    SOURCE_TASK     VARCHAR(200),
    FAILED_AT       TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    RETRY_COUNT     NUMBER DEFAULT 0,
    MAX_RETRIES     NUMBER DEFAULT 3,
    IS_RESOLVED     BOOLEAN DEFAULT FALSE,
    RESOLVED_AT     TIMESTAMP_NTZ,
    RESOLVED_BY     VARCHAR(100)
);

-- Evaluation tables
CREATE OR REPLACE TABLE CLAIMGUARD.APP.GOLD_SET (
    GOLD_ID         NUMBER AUTOINCREMENT PRIMARY KEY,
    CLAIM_ID        NUMBER NOT NULL,
    REQUIREMENT_CODE VARCHAR(50) NOT NULL,
    EXPECTED_STATUS VARCHAR(30) NOT NULL,
    EXPECTED_REASON VARCHAR(1000),
    LABEL_SOURCE    VARCHAR(50) DEFAULT 'AUTOMATED',
    CREATED_AT      TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE OR REPLACE TABLE CLAIMGUARD.APP.EVALUATION_RESULTS (
    RESULT_ID       NUMBER AUTOINCREMENT PRIMARY KEY,
    EVAL_ID         NUMBER NOT NULL,
    CLAIM_ID        NUMBER NOT NULL,
    REQUIREMENT_CODE VARCHAR(50) NOT NULL,
    EXPECTED_STATUS VARCHAR(30),
    ACTUAL_STATUS   VARCHAR(30),
    IS_CORRECT      BOOLEAN,
    ACTUAL_FINDING  VARCHAR(5000),
    ACTUAL_CITATION VARCHAR(1000),
    CREATED_AT      TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE OR REPLACE TABLE CLAIMGUARD.APP.EVALUATION_RUNS (
    EVAL_ID         NUMBER AUTOINCREMENT PRIMARY KEY,
    RUN_NAME        VARCHAR(200) NOT NULL,
    TOTAL_CASES     NUMBER,
    TRUE_POSITIVES  NUMBER DEFAULT 0,
    FALSE_POSITIVES NUMBER DEFAULT 0,
    TRUE_NEGATIVES  NUMBER DEFAULT 0,
    FALSE_NEGATIVES NUMBER DEFAULT 0,
    PRECISION_SCORE NUMBER(5,4),
    RECALL_SCORE    NUMBER(5,4),
    F1_SCORE        NUMBER(5,4),
    CITATION_CORRECT NUMBER DEFAULT 0,
    CITATION_TOTAL  NUMBER DEFAULT 0,
    CITATION_ACCURACY NUMBER(5,4),
    PROCESSING_TIME_MS NUMBER,
    CREATED_AT      TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
