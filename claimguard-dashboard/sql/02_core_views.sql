CREATE OR REPLACE VIEW CLAIMGUARD.CORE.PATIENTS AS
SELECT PATIENT_ID, FIRST || ' ' || LAST AS FULL_NAME, BIRTHDATE, DEATHDATE,
       GENDER, RACE, ETHNICITY, MARITAL, ADDRESS, CITY, STATE, COUNTY, ZIP,
       LAT, LON, HEALTHCARE_EXPENSES, HEALTHCARE_COVERAGE, INCOME
FROM SYNTHETIC_HEALTHCARE_DATA_CLINICAL_AND_CLAIMS.SILVER.PATIENTS;

CREATE OR REPLACE VIEW CLAIMGUARD.CORE.ENCOUNTERS AS
SELECT ENCOUNTER_ID, PATIENT_ID, ORGANIZATION_ID, PROVIDER_ID, PAYER_ID,
       ENCOUNTER_START, ENCOUNTER_STOP, ENCOUNTERCLASS,
       CODE AS ENCOUNTER_CODE, DESCRIPTION AS ENCOUNTER_DESCRIPTION,
       BASE_ENCOUNTER_COST, TOTAL_CLAIM_COST, PAYER_COVERAGE,
       REASONCODE, REASONDESCRIPTION
FROM SYNTHETIC_HEALTHCARE_DATA_CLINICAL_AND_CLAIMS.SILVER.ENCOUNTERS;

CREATE OR REPLACE VIEW CLAIMGUARD.CORE.CLAIMS AS
SELECT CLAIM_ID, PATIENT_ID, PROVIDER_ID, ENCOUNTER_ID,
       PRIMARY_PATIENT_INSURANCE_ID AS PAYER_ID, SERVICEDATE, CURRENTILLNESSDATE,
       DIAGNOSIS1, DIAGNOSIS2, DIAGNOSIS3, DIAGNOSIS4,
       DIAGNOSIS5, DIAGNOSIS6, DIAGNOSIS7, DIAGNOSIS8,
       REFERRING_PROVIDER_ID, SUPERVISING_PROVIDER_ID,
       STATUS1 AS PRIMARY_STATUS, OUTSTANDING1 AS PRIMARY_OUTSTANDING,
       HEALTHCARECLAIMTYPEID1 AS CLAIM_TYPE, LASTBILLEDDATE1 AS LAST_BILLED_DATE
FROM SYNTHETIC_HEALTHCARE_DATA_CLINICAL_AND_CLAIMS.SILVER.CLAIMS;

CREATE OR REPLACE VIEW CLAIMGUARD.CORE.CLAIM_LINES AS
SELECT CLAIMS_TX_ID AS CLAIM_LINE_ID, CLAIM_ID, PATIENT_ID, ENCOUNTER_ID,
       PROVIDER_ID, TYPE AS LINE_TYPE, AMOUNT, PROCEDURECODE,
       NOTES AS DESCRIPTION, UNITS, UNITAMOUNT,
       FROMDATE AS SERVICE_FROM, TODATE AS SERVICE_TO,
       PAYMENTS, ADJUSTMENTS, OUTSTANDING
FROM SYNTHETIC_HEALTHCARE_DATA_CLINICAL_AND_CLAIMS.SILVER.CLAIMS_TX;

CREATE OR REPLACE VIEW CLAIMGUARD.CORE.DIAGNOSES AS
SELECT CONDITION_ID AS DIAGNOSIS_ID, PATIENT_ID, ENCOUNTER_ID,
       CODE AS DIAGNOSIS_CODE, DESCRIPTION AS DIAGNOSIS_DESCRIPTION,
       SYSTEM AS CODE_SYSTEM, CONDITION_START AS ONSET_DATE,
       CONDITION_STOP AS RESOLUTION_DATE
FROM SYNTHETIC_HEALTHCARE_DATA_CLINICAL_AND_CLAIMS.SILVER.CONDITIONS;

CREATE OR REPLACE VIEW CLAIMGUARD.CORE.OBSERVATIONS AS
SELECT OBSERVATION_ID, PATIENT_ID, ENCOUNTER_ID, OBSERVATION_DATE,
       CATEGORY, CODE AS OBSERVATION_CODE, DESCRIPTION AS OBSERVATION_DESCRIPTION,
       VALUE, UNITS, TYPE AS VALUE_TYPE
FROM SYNTHETIC_HEALTHCARE_DATA_CLINICAL_AND_CLAIMS.SILVER.OBSERVATIONS;

CREATE OR REPLACE VIEW CLAIMGUARD.CORE.CLINICAL_EVIDENCE AS
SELECT OBSERVATION_ID AS EVIDENCE_ID, PATIENT_ID, ENCOUNTER_ID,
       'OBSERVATION' AS EVIDENCE_TYPE, CODE AS EVIDENCE_CODE,
       DESCRIPTION AS EVIDENCE_DESCRIPTION, VALUE AS EVIDENCE_VALUE,
       UNITS AS EVIDENCE_UNITS, OBSERVATION_DATE AS EVIDENCE_DATE
FROM SYNTHETIC_HEALTHCARE_DATA_CLINICAL_AND_CLAIMS.SILVER.OBSERVATIONS
UNION ALL
SELECT PROCEDURE_ID, PATIENT_ID, ENCOUNTER_ID, 'PROCEDURE',
       CAST(CODE AS VARCHAR), DESCRIPTION, NULL, NULL, PROC_START
FROM SYNTHETIC_HEALTHCARE_DATA_CLINICAL_AND_CLAIMS.SILVER.PROCEDURES
UNION ALL
SELECT DEVICE_ID, PATIENT_ID, ENCOUNTER_ID, 'DEVICE',
       CAST(CODE AS VARCHAR), DESCRIPTION, UDI, NULL, DEVICE_START
FROM SYNTHETIC_HEALTHCARE_DATA_CLINICAL_AND_CLAIMS.SILVER.DEVICES
UNION ALL
SELECT MEDICATION_ID, PATIENT_ID, ENCOUNTER_ID, 'MEDICATION',
       CAST(CODE AS VARCHAR), DESCRIPTION, CAST(DISPENSES AS VARCHAR), NULL, MED_START
FROM SYNTHETIC_HEALTHCARE_DATA_CLINICAL_AND_CLAIMS.SILVER.MEDICATIONS;

-- Clinical notes table (AI-generated notes stored here)
CREATE TABLE IF NOT EXISTS CLAIMGUARD.CORE.CLINICAL_NOTES (
    NOTE_ID         NUMBER AUTOINCREMENT PRIMARY KEY,
    CLAIM_ID        NUMBER NOT NULL,
    PATIENT_ID      NUMBER NOT NULL,
    ENCOUNTER_ID    NUMBER NOT NULL,
    NOTE_TYPE       VARCHAR(50),
    NOTE_DATE       TIMESTAMP_NTZ,
    NOTE_TEXT       VARCHAR(16777216) NOT NULL,
    GENERATED_BY    VARCHAR(50) DEFAULT 'AI_COMPLETE',
    CREATED_AT      TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
