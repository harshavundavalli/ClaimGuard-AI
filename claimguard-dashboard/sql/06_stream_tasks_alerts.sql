-- ============================================================
-- ClaimGuard AI — Deployment Script 6: Stream, Tasks, Alerts
-- Prerequisites: Scripts 01, 05
-- ============================================================

-- Stream on incoming claims
CREATE OR REPLACE STREAM CLAIMGUARD.RAW.NEW_CLAIMS_STREAM
    ON TABLE CLAIMGUARD.RAW.INCOMING_CLAIMS
    SHOW_INITIAL_ROWS = FALSE
    COMMENT = 'Detects new incoming claims for review queue processing';

-- Main task: queue valid claims
CREATE OR REPLACE TASK CLAIMGUARD.APP.QUEUE_NEW_CLAIMS
    WAREHOUSE = COMPUTE_WH
    SCHEDULE = '5 MINUTE'
    COMMENT = 'Moves new incoming claims into the review queue with deduplication and validation'
    WHEN SYSTEM$STREAM_HAS_DATA('CLAIMGUARD.RAW.NEW_CLAIMS_STREAM')
AS
    INSERT INTO CLAIMGUARD.APP.REVIEW_QUEUE (CLAIM_ID, PATIENT_ID, ENCOUNTER_ID, QUEUE_STATUS, PRIORITY, EVENT_ID)
    SELECT s.CLAIM_ID, s.PATIENT_ID, s.ENCOUNTER_ID, 'PENDING', 5,
           'EVT-' || s.RAW_CLAIM_ID || '-' || TO_CHAR(CURRENT_TIMESTAMP(), 'YYYYMMDDHHMMSS')
    FROM CLAIMGUARD.RAW.NEW_CLAIMS_STREAM s
    WHERE s.METADATA$ACTION = 'INSERT'
    AND s.CLAIM_ID IS NOT NULL AND s.PATIENT_ID IS NOT NULL AND s.ENCOUNTER_ID IS NOT NULL
    AND NOT EXISTS (
        SELECT 1 FROM CLAIMGUARD.APP.REVIEW_QUEUE q
        WHERE q.CLAIM_ID = s.CLAIM_ID AND q.QUEUE_STATUS IN ('PENDING', 'RUNNING')
    );

-- Child task: route invalid records to DLQ
CREATE OR REPLACE TASK CLAIMGUARD.APP.ROUTE_INVALID_CLAIMS
    WAREHOUSE = COMPUTE_WH
    AFTER CLAIMGUARD.APP.QUEUE_NEW_CLAIMS
AS
    INSERT INTO CLAIMGUARD.APP.DEAD_LETTER_QUEUE (CLAIM_ID, PATIENT_ID, ENCOUNTER_ID, ERROR_MESSAGE, SOURCE_TASK)
    SELECT CLAIM_ID, PATIENT_ID, ENCOUNTER_ID, 'Missing required field', 'ROUTE_INVALID_CLAIMS'
    FROM CLAIMGUARD.RAW.INCOMING_CLAIMS
    WHERE IS_PROCESSED = FALSE
    AND (CLAIM_ID IS NULL OR PATIENT_ID IS NULL OR ENCOUNTER_ID IS NULL);

-- Alert: failed claims exceeding max retries
CREATE OR REPLACE ALERT CLAIMGUARD.APP.FAILED_CLAIMS_ALERT
    WAREHOUSE = COMPUTE_WH
    SCHEDULE = '60 MINUTE'
    IF (EXISTS (
        SELECT 1 FROM CLAIMGUARD.APP.REVIEW_QUEUE
        WHERE QUEUE_STATUS = 'FAILED' AND RETRY_COUNT >= MAX_RETRIES
        AND QUEUED_AT > DATEADD('day', -1, CURRENT_TIMESTAMP())
    ))
    THEN
        INSERT INTO CLAIMGUARD.APP.PIPELINE_RUNS (RUN_TYPE, RUN_STATUS, CLAIMS_FAILED, ERROR_LOG)
        SELECT 'ALERT_FAILED_CLAIMS', 'ALERT_FIRED', COUNT(*),
               'Alert: ' || COUNT(*) || ' claims exceeded max retries in last 24 hours.'
        FROM CLAIMGUARD.APP.REVIEW_QUEUE
        WHERE QUEUE_STATUS = 'FAILED' AND RETRY_COUNT >= MAX_RETRIES
        AND QUEUED_AT > DATEADD('day', -1, CURRENT_TIMESTAMP());

-- Alert: unresolved dead-letter items
CREATE OR REPLACE ALERT CLAIMGUARD.APP.DLQ_ALERT
    WAREHOUSE = COMPUTE_WH
    SCHEDULE = '60 MINUTE'
    IF (EXISTS (
        SELECT 1 FROM CLAIMGUARD.APP.DEAD_LETTER_QUEUE
        WHERE IS_RESOLVED = FALSE
        AND FAILED_AT > DATEADD('day', -1, CURRENT_TIMESTAMP())
    ))
    THEN
        INSERT INTO CLAIMGUARD.APP.PIPELINE_RUNS (RUN_TYPE, RUN_STATUS, CLAIMS_FAILED, ERROR_LOG)
        SELECT 'ALERT_DLQ', 'ALERT_FIRED', COUNT(*),
               'Alert: ' || COUNT(*) || ' unresolved dead-letter items in last 24 hours.'
        FROM CLAIMGUARD.APP.DEAD_LETTER_QUEUE
        WHERE IS_RESOLVED = FALSE
        AND FAILED_AT > DATEADD('day', -1, CURRENT_TIMESTAMP());

-- Resume all
ALTER TASK CLAIMGUARD.APP.ROUTE_INVALID_CLAIMS RESUME;
ALTER TASK CLAIMGUARD.APP.QUEUE_NEW_CLAIMS RESUME;
ALTER ALERT CLAIMGUARD.APP.FAILED_CLAIMS_ALERT RESUME;
ALTER ALERT CLAIMGUARD.APP.DLQ_ALERT RESUME;
