-- ============================================================
-- ClaimGuard AI — Deployment Script 8: RBAC and Cost Controls
-- Prerequisites: Script 01, warehouse COMPUTE_WH exists
-- ============================================================

-- Create roles
CREATE ROLE IF NOT EXISTS CLAIMGUARD_SERVICE;
CREATE ROLE IF NOT EXISTS CLAIMGUARD_REVIEWER;
CREATE ROLE IF NOT EXISTS CLAIMGUARD_ADMIN;

-- Role hierarchy
GRANT ROLE CLAIMGUARD_SERVICE TO ROLE CLAIMGUARD_ADMIN;
GRANT ROLE CLAIMGUARD_REVIEWER TO ROLE CLAIMGUARD_ADMIN;
GRANT ROLE CLAIMGUARD_ADMIN TO ROLE ACCOUNTADMIN;

-- SERVICE role grants
GRANT USAGE ON DATABASE CLAIMGUARD TO ROLE CLAIMGUARD_SERVICE;
GRANT USAGE ON SCHEMA CLAIMGUARD.RAW TO ROLE CLAIMGUARD_SERVICE;
GRANT USAGE ON SCHEMA CLAIMGUARD.CORE TO ROLE CLAIMGUARD_SERVICE;
GRANT USAGE ON SCHEMA CLAIMGUARD.RAG TO ROLE CLAIMGUARD_SERVICE;
GRANT USAGE ON SCHEMA CLAIMGUARD.APP TO ROLE CLAIMGUARD_SERVICE;
GRANT SELECT ON ALL VIEWS IN SCHEMA CLAIMGUARD.CORE TO ROLE CLAIMGUARD_SERVICE;
GRANT SELECT ON ALL TABLES IN SCHEMA CLAIMGUARD.RAG TO ROLE CLAIMGUARD_SERVICE;
GRANT SELECT, INSERT ON TABLE CLAIMGUARD.RAW.INCOMING_CLAIMS TO ROLE CLAIMGUARD_SERVICE;
GRANT SELECT, INSERT, UPDATE ON TABLE CLAIMGUARD.APP.REVIEW_QUEUE TO ROLE CLAIMGUARD_SERVICE;
GRANT INSERT ON TABLE CLAIMGUARD.APP.CLAIM_REVIEWS TO ROLE CLAIMGUARD_SERVICE;
GRANT INSERT ON TABLE CLAIMGUARD.APP.REVIEW_FINDINGS TO ROLE CLAIMGUARD_SERVICE;
GRANT INSERT ON TABLE CLAIMGUARD.APP.PIPELINE_RUNS TO ROLE CLAIMGUARD_SERVICE;
GRANT USAGE ON FUNCTION CLAIMGUARD.APP.CHECK_CLAIM_REQUIREMENTS(NUMBER) TO ROLE CLAIMGUARD_SERVICE;
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE CLAIMGUARD_SERVICE;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE CLAIMGUARD_SERVICE;

-- REVIEWER role grants
GRANT USAGE ON DATABASE CLAIMGUARD TO ROLE CLAIMGUARD_REVIEWER;
GRANT USAGE ON SCHEMA CLAIMGUARD.CORE TO ROLE CLAIMGUARD_REVIEWER;
GRANT USAGE ON SCHEMA CLAIMGUARD.RAG TO ROLE CLAIMGUARD_REVIEWER;
GRANT USAGE ON SCHEMA CLAIMGUARD.APP TO ROLE CLAIMGUARD_REVIEWER;
GRANT SELECT ON ALL VIEWS IN SCHEMA CLAIMGUARD.CORE TO ROLE CLAIMGUARD_REVIEWER;
GRANT SELECT ON ALL TABLES IN SCHEMA CLAIMGUARD.RAG TO ROLE CLAIMGUARD_REVIEWER;
GRANT SELECT ON TABLE CLAIMGUARD.APP.REVIEW_QUEUE TO ROLE CLAIMGUARD_REVIEWER;
GRANT SELECT ON TABLE CLAIMGUARD.APP.CLAIM_REVIEWS TO ROLE CLAIMGUARD_REVIEWER;
GRANT SELECT ON TABLE CLAIMGUARD.APP.REVIEW_FINDINGS TO ROLE CLAIMGUARD_REVIEWER;
GRANT SELECT ON TABLE CLAIMGUARD.APP.REVIEW_ACTIONS TO ROLE CLAIMGUARD_REVIEWER;
GRANT SELECT ON TABLE CLAIMGUARD.APP.PIPELINE_RUNS TO ROLE CLAIMGUARD_REVIEWER;
GRANT INSERT ON TABLE CLAIMGUARD.APP.REVIEW_ACTIONS TO ROLE CLAIMGUARD_REVIEWER;
GRANT USAGE ON FUNCTION CLAIMGUARD.APP.CHECK_CLAIM_REQUIREMENTS(NUMBER) TO ROLE CLAIMGUARD_REVIEWER;
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE CLAIMGUARD_REVIEWER;

-- ADMIN role grants
GRANT USAGE ON DATABASE CLAIMGUARD TO ROLE CLAIMGUARD_ADMIN;
GRANT USAGE ON ALL SCHEMAS IN DATABASE CLAIMGUARD TO ROLE CLAIMGUARD_ADMIN;
GRANT ALL ON ALL TABLES IN SCHEMA CLAIMGUARD.RAW TO ROLE CLAIMGUARD_ADMIN;
GRANT SELECT ON ALL VIEWS IN SCHEMA CLAIMGUARD.CORE TO ROLE CLAIMGUARD_ADMIN;
GRANT ALL ON ALL TABLES IN SCHEMA CLAIMGUARD.RAG TO ROLE CLAIMGUARD_ADMIN;
GRANT ALL ON ALL TABLES IN SCHEMA CLAIMGUARD.APP TO ROLE CLAIMGUARD_ADMIN;
GRANT USAGE ON FUNCTION CLAIMGUARD.APP.CHECK_CLAIM_REQUIREMENTS(NUMBER) TO ROLE CLAIMGUARD_ADMIN;
GRANT USAGE ON PROCEDURE CLAIMGUARD.APP.RUN_EVALUATION(NUMBER) TO ROLE CLAIMGUARD_ADMIN;
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE CLAIMGUARD_ADMIN;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE CLAIMGUARD_ADMIN;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_AGENT_USER TO ROLE CLAIMGUARD_ADMIN;

-- Cost controls
ALTER WAREHOUSE COMPUTE_WH SET AUTO_SUSPEND = 60 AUTO_RESUME = TRUE;

CREATE OR REPLACE RESOURCE MONITOR CLAIMGUARD_MONITOR
    WITH CREDIT_QUOTA = 100
    FREQUENCY = MONTHLY
    START_TIMESTAMP = IMMEDIATELY
    TRIGGERS
        ON 75 PERCENT DO NOTIFY
        ON 90 PERCENT DO NOTIFY
        ON 100 PERCENT DO SUSPEND;

ALTER WAREHOUSE COMPUTE_WH SET RESOURCE_MONITOR = CLAIMGUARD_MONITOR;

-- Cortex Search auto-suspend
ALTER CORTEX SEARCH SERVICE CLAIMGUARD.RAG.POLICY_SEARCH_SERVICE SET AUTO_SUSPEND = 1800;
